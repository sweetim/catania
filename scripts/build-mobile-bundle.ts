/**
 * Builds the Catania web app into a single self-contained offline HTML module
 * for the Expo iOS/Android WebView shell (`mobile/generated/webBundle.ts`).
 */
import tailwind from "bun-plugin-tailwind";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const rootDirectory = process.cwd();
const temporaryOutdir = path.join(rootDirectory, "mobile", ".web-build-tmp");
const outputFile = path.join(rootDirectory, "mobile", "generated", "webBundle.ts");

await rm(temporaryOutdir, { recursive: true, force: true });

const buildResult = await Bun.build({
  entrypoints: [path.join(rootDirectory, "src", "index.html")],
  outdir: temporaryOutdir,
  plugins: [tailwind],
  minify: true,
  target: "browser",
  define: {
    "process.env.NODE_ENV": JSON.stringify("production"),
  },
});

if (!buildResult.success) {
  for (const log of buildResult.logs) {
    console.error(log);
  }
  process.exit(1);
}

const htmlPath = path.join(temporaryOutdir, "index.html");
let html = await readFile(htmlPath, "utf8");

// Inline all built stylesheets into <style> tags.
const inlinedAssets: { name: string; content: string }[] = [];
const stylesheetMatches = [...html.matchAll(/<link\b[^>]*rel=["']stylesheet["'][^>]*href=["']([^"']+)["'][^>]*>/gi)];
for (const stylesheetMatch of stylesheetMatches) {
  const fullTag = stylesheetMatch[0];
  const href = stylesheetMatch[1];
  if (!href || href.startsWith("http://") || href.startsWith("https://")) continue;
  const assetPath = path.join(temporaryOutdir, href.replace(/^\.?\//, ""));
  const cssContent = (await readFile(assetPath, "utf8")).replace(/<\/style/gi, "<\\/style");
  html = html.replace(fullTag, () => `<style>${cssContent}</style>`);
  inlinedAssets.push({ name: href, content: cssContent });
}

// Inline all built module scripts into <script type="module"> tags.
const scriptMatches = [...html.matchAll(/<script\b[^>]*src=["']([^"']+)["'][^>]*><\/script>/gi)];
for (const scriptMatch of scriptMatches) {
  const fullTag = scriptMatch[0];
  const source = scriptMatch[1];
  if (!source || source.startsWith("http://") || source.startsWith("https://")) continue;
  const assetPath = path.join(temporaryOutdir, source.replace(/^\.?\//, ""));
  const javascriptContent = (await readFile(assetPath, "utf8")).replace(/<\/script/gi, "<\\/script");
  html = html.replace(fullTag, () => `<script type="module">${javascriptContent}</script>`);
  inlinedAssets.push({ name: source, content: javascriptContent });
}

// Mark the WebView runtime as native before the app boots so setupPwa() and native bridges initialize cleanly.
html = html.replace(
  "<head>",
  "<head><script>window.__CATANIA_NATIVE_APP__=true;</script>",
);

const modifiedAsset = inlinedAssets.find(({ content }) => !html.includes(content));
if (modifiedAsset) {
  await rm(temporaryOutdir, { recursive: true, force: true });
  console.error(`Inlining modified ${modifiedAsset.name}; aborting instead of writing a broken bundle.`);
  process.exit(1);
}

await mkdir(path.dirname(outputFile), { recursive: true });
const moduleContents = `// Auto-generated by scripts/build-mobile-bundle.ts — do not edit manually.\nexport const CATANIA_WEB_BUNDLE_HTML = ${JSON.stringify(html)};\n`;
await writeFile(outputFile, moduleContents, "utf8");
await rm(temporaryOutdir, { recursive: true, force: true });

console.log(` ${path.relative(rootDirectory, outputFile)}  ${(Buffer.byteLength(moduleContents, "utf8") / 1024).toFixed(1)} KB`);
